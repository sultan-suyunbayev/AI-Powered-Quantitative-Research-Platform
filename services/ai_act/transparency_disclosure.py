@dataclass
class DisclosureAuditRecord:
    """Audit record for disclosure tracking."""
    record_id: str
    disclosure_id: str
    user_id: str
    action: str  # created, shown, acknowledged, revoked
    timestamp: datetime
    context: DisclosureContext
    metadata: Dict[str, Any] = field(default_factory=dict)


class TransparencyDisclosureManager:
    """
    Manages Article 50 transparency disclosures.

    Responsibilities:
    1. Generate disclosure content in multiple languages
    2. Track user acknowledgments
    3. Provide audit trail for compliance verification
    4. Add API response headers per Article 50
    5. Verify disclosure requirements are met

    Example:
        >>> manager = create_transparency_manager()
        >>> disclosure = manager.create_disclosure("user123", DisclosureContext.REGISTRATION)
        >>> text = disclosure.generate_disclosure_text("en")
        >>> print(text["header"])
        AI SYSTEM DISCLOSURE
    """

    def __init__(self, storage_backend: Optional[Dict] = None):
        """
        Initialize the transparency disclosure manager.

        Args:
            storage_backend: Optional storage backend for persistence
        """
        self.storage = storage_backend or {}
        self.disclosures: Dict[str, AIDisclosure] = {}
        self.audit_log: List[DisclosureAuditRecord] = []
        self._user_disclosures: Dict[str, List[str]] = {}  # user_id -> disclosure_ids

    def create_disclosure(
        self,
        user_id: str,
        context: DisclosureContext,
        disclosure_type: DisclosureType = DisclosureType.AI_INTERACTION,
        ip_address: Optional[str] = None,
        user_agent: Optional[str] = None
    ) -> AIDisclosure:
        """
        Create new disclosure for user context.

        Args:
            user_id: Unique user identifier
            context: Context where disclosure is shown
            disclosure_type: Type of disclosure per Article 50
            ip_address: Optional IP for audit trail
            user_agent: Optional user agent for audit trail

        Returns:
            AIDisclosure instance
        """
        disclosure_id = self._generate_id(user_id, context)

        disclosure = AIDisclosure(
            disclosure_id=disclosure_id,
            disclosure_type=disclosure_type,
            context=context,
            timestamp=datetime.utcnow(),
            user_id=user_id,
            ip_address=ip_address,
            user_agent=user_agent
        )

        self.disclosures[disclosure_id] = disclosure

        # Track user's disclosures
        if user_id not in self._user_disclosures:
            self._user_disclosures[user_id] = []
        self._user_disclosures[user_id].append(disclosure_id)

        # Audit log
        self._log_action(disclosure_id, user_id, "created", context)

        return disclosure

    def record_acknowledgment(
        self,
        disclosure_id: str,
        user_id: str,
        ip_address: Optional[str] = None,
        user_agent: Optional[str] = None
    ) -> bool:
        """
        Record user acknowledgment of AI disclosure.

        Args:
            disclosure_id: The disclosure being acknowledged
            user_id: User acknowledging the disclosure
            ip_address: Optional IP for audit trail
            user_agent: Optional user agent for audit trail

        Returns:
            True if acknowledgment recorded, False if failed
        """
        if disclosure_id not in self.disclosures:
            return False

        disclosure = self.disclosures[disclosure_id]

        # Verify user owns this disclosure
        if disclosure.user_id != user_id:
            return False

        disclosure.acknowledged = True
        disclosure.acknowledgment_timestamp = datetime.utcnow()

        # Audit log
        self._log_action(
            disclosure_id,
            user_id,
            "acknowledged",
            disclosure.context,
            metadata={"ip_address": ip_address, "user_agent": user_agent}
        )

        return True

    def check_disclosure_required(
        self,
        user_id: str,
        context: DisclosureContext
    ) -> bool:
        """
        Check if disclosure is required for this context.

        Args:
            user_id: User to check
            context: Context to check

        Returns:
            True if disclosure is required, False otherwise
        """
        # Find requirement for this context
        requirement = self._get_requirement(context)
        if not requirement or not requirement.required:
            return False

        # Check if already acknowledged
        disclosure_id = self._generate_id(user_id, context)
        if disclosure_id in self.disclosures:
            return not self.disclosures[disclosure_id].acknowledged

        return True

    def get_user_disclosures(
        self,
        user_id: str,
        context: Optional[DisclosureContext] = None
    ) -> List[AIDisclosure]:
        """
        Get all disclosures for a user.

        Args:
            user_id: User to get disclosures for
            context: Optional filter by context

        Returns:
            List of AIDisclosure instances
        """
        disclosure_ids = self._user_disclosures.get(user_id, [])
        disclosures = [
            self.disclosures[did]
            for did in disclosure_ids
            if did in self.disclosures
        ]

        if context:
            disclosures = [d for d in disclosures if d.context == context]

        return disclosures

    def get_api_headers(self) -> Dict[str, str]:
        """
        Return HTTP headers for API responses per Article 50.

        These headers must be included in all API responses that
        return AI-generated content.

        Returns:
            Dictionary of headers to add to API responses
        """
        return {
            "X-AI-System": "true",
            "X-AI-Model": "Distributional-PPO-v1",
            "X-AI-Model-Type": "Reinforcement-Learning",
            "X-AI-Disclosure": "This response is generated by an AI system",
            "X-AI-Act-Compliance": "Article-50",
            "X-AI-Provider": "AI-Powered-Quantitative-Research-Platform",
        }

    def get_api_response_metadata(self) -> Dict[str, Any]:
        """
        Get metadata to include in API response body.

        Returns:
            Dictionary with AI system metadata
        """
        return {
            "_ai_disclosure": {
                "is_ai_generated": True,
                "model_name": "Distributional PPO Trading Model",
                "model_type": "Reinforcement Learning",
                "compliance": "EU AI Act Article 50",
                "notice": "This content is generated by an AI system",
                "timestamp": datetime.utcnow().isoformat(),
            }
        }

    def verify_compliance(self, user_id: str) -> Dict[str, Any]:
        """
        Verify Article 50 compliance status for a user.

        Args:
            user_id: User to verify

        Returns:
            Dictionary with compliance status
        """
        user_disclosures = self.get_user_disclosures(user_id)

        # Check each required context
        compliance_status = {}
        for req in DISCLOSURE_REQUIREMENTS:
            if not req.required:
                continue

            context_disclosures = [
                d for d in user_disclosures
                if d.context == req.context
            ]

            if context_disclosures:
                latest = max(context_disclosures, key=lambda d: d.timestamp)
                compliance_status[req.context.value] = {
                    "disclosed": True,
                    "acknowledged": latest.acknowledged,
                    "timestamp": latest.timestamp.isoformat(),
                    "blocking": req.blocking and not latest.acknowledged,
                }
            else:
                compliance_status[req.context.value] = {
                    "disclosed": False,
                    "acknowledged": False,
                    "timestamp": None,
                    "blocking": req.blocking,
                }

        all_acknowledged = all(
            s.get("acknowledged", False)
            for s in compliance_status.values()
        )

        return {
            "user_id": user_id,
            "article_50_compliant": all_acknowledged,
            "contexts": compliance_status,
            "verification_timestamp": datetime.utcnow().isoformat(),
        }

    def get_audit_trail(
        self,
        user_id: Optional[str] = None,
        start_date: Optional[datetime] = None,
        end_date: Optional[datetime] = None
    ) -> List[Dict[str, Any]]:
        """
        Get audit trail for disclosures.

        Args:
            user_id: Optional filter by user
            start_date: Optional start date filter
            end_date: Optional end date filter

        Returns:
            List of audit records
        """
        records = self.audit_log

        if user_id:
            records = [r for r in records if r.user_id == user_id]
        if start_date:
            records = [r for r in records if r.timestamp >= start_date]
        if end_date:
            records = [r for r in records if r.timestamp <= end_date]

        return [
            {
                "record_id": r.record_id,
                "disclosure_id": r.disclosure_id,
                "user_id": r.user_id,
                "action": r.action,
                "timestamp": r.timestamp.isoformat(),
                "context": r.context.value,
                "metadata": r.metadata,
            }
            for r in records
        ]

    def _generate_id(self, user_id: str, context: DisclosureContext) -> str:
        """Generate unique disclosure ID."""
        data = f"{user_id}:{context.value}"
        return hashlib.sha256(data.encode()).hexdigest()[:16]

    def _get_requirement(
        self,
        context: DisclosureContext
    ) -> Optional[DisclosureRequirement]:
        """Get requirement for a context."""
        for req in DISCLOSURE_REQUIREMENTS:
            if req.context == context:
                return req
        return None

    def _log_action(
        self,
        disclosure_id: str,
        user_id: str,
        action: str,
        context: DisclosureContext,
        metadata: Optional[Dict[str, Any]] = None
    ) -> None:
        """Log action to audit trail."""
        record = DisclosureAuditRecord(
            record_id=hashlib.sha256(
                f"{disclosure_id}:{action}:{datetime.utcnow().isoformat()}".encode()
            ).hexdigest()[:16],
            disclosure_id=disclosure_id,
            user_id=user_id,
            action=action,
            timestamp=datetime.utcnow(),
            context=context,
            metadata=metadata or {}
        )
        self.audit_log.append(record)


class SyntheticContentMarker:
    """
    Article 50(2) - Synthetic Content Marking.

    Marks AI-generated content (reports, analysis, etc.) as synthetic.
    """

    MARKER_PREFIX = "[AI-GENERATED]"

    @staticmethod
    def mark_content(content: str, include_footer: bool = True) -> str:
        """
        Mark content as AI-generated.

        Args:
            content: The content to mark
            include_footer: Whether to add footer notice

        Returns:
            Content with AI generation markers
        """
        marked = f"{SyntheticContentMarker.MARKER_PREFIX}\n{content}"

        if include_footer:
            footer = (
                "\n\n---\n"
                "*This content was generated by an AI system. "
                "Per Article 50(2) of the EU AI Act, AI-generated "
                "content must be clearly marked.*"
            )
            marked += footer

        return marked

    @staticmethod
    def add_metadata(data: Dict[str, Any]) -> Dict[str, Any]:
        """
        Add AI generation metadata to a data structure.

        Args:
            data: Dictionary to add metadata to

        Returns:
            Dictionary with metadata added
        """
        data["_synthetic_content"] = {
            "is_ai_generated": True,
            "generator": "Distributional PPO Trading Model",
            "compliance": "EU AI Act Article 50(2)",
            "generated_at": datetime.utcnow().isoformat(),
        }
        return data

    @staticmethod
    def is_marked(content: str) -> bool:
        """Check if content is already marked."""
        return content.startswith(SyntheticContentMarker.MARKER_PREFIX)


