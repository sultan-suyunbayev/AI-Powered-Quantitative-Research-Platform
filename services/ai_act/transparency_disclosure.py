@dataclass
class DisclosureRequirement:
    """
    Defines when disclosure is required per Article 50.

    Attributes:
        context: The context requiring disclosure
        required: Whether disclosure is mandatory
        reason: Why disclosure is required
        article_reference: The specific article/recital reference
        blocking: Whether to block access until acknowledged
    """
    context: DisclosureContext
    required: bool
    reason: str
    article_reference: str
    blocking: bool = True


