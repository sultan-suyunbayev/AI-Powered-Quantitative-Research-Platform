# -*- coding: utf-8 -*-
"""
Article 50 EU AI Act - Transparency Disclosure System.

This module implements the transparency requirements for AI systems
as mandated by Article 50 of the EU AI Act (Regulation (EU) 2024/1689).

Key Requirements:
- Article 50(1): AI interaction disclosure - Users must be informed they
  are interacting with an AI system
- Article 50(2): Synthetic content marking
- Article 50(3): Emotion recognition disclosure
- Article 50(4): Deep fake marking

References:
    - EU AI Act Article 50: https://artificialintelligenceact.eu/article/50/
    - Recital 132: Transparency for limited-risk AI
    - GPAI Code of Practice Chapter on Transparency
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Optional, Dict, List, Any
import hashlib
import json


class DisclosureType(Enum):
    """
    Article 50 disclosure categories.

    Each type corresponds to specific requirements under Article 50.
    """
    AI_INTERACTION = "ai_interaction"       # Art. 50(1) - Basic AI interaction
    SYNTHETIC_CONTENT = "synthetic_content"  # Art. 50(2) - AI-generated content
    EMOTION_RECOGNITION = "emotion_recognition"  # Art. 50(3) - Emotion detection
    DEEP_FAKE = "deep_fake"                 # Art. 50(4) - Manipulated media


class DisclosureContext(Enum):
    """
    Context where disclosure is shown to user.

    Different contexts may require different levels of disclosure.
    """
    REGISTRATION = "registration"
    STRATEGY_CREATION = "strategy_creation"
    LIVE_TRADING_ACTIVATION = "live_trading_activation"
    MODEL_OUTPUT = "model_output"
    API_RESPONSE = "api_response"
    DASHBOARD = "dashboard"
    REPORT_GENERATION = "report_generation"


class DisclosureLanguage(Enum):
    """Supported languages for disclosure texts."""
    ENGLISH = "en"
    RUSSIAN = "ru"
    GERMAN = "de"
    FRENCH = "fr"
    DUTCH = "nl"


